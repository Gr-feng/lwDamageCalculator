# ===================== 2. 解析BUFF的函数 =====================
def parse_buff(buff_arr):
    """
    解析buff数组，返回由5个int组成的二维列表（忽略原始数值）
    :param buff_arr: 扁平的buff数组，如 [25, 100]
    :return: 二维列表，如 [[1,1,6,1,1]]
    """
    # 异常处理：非列表/空列表/长度非偶数，返回空列表
    if not isinstance(buff_arr, list) or len(buff_arr) == 0 or len(buff_arr) % 2 != 0:
        print("buff数组格式错误：非列表/空列表/长度非偶数")
        return []
    
    result = []
    # 步长2遍历，取每个组的第一个元素（buff ID），忽略第二个数值
    for i in range(0, len(buff_arr), 2):
        buff_id = buff_arr[i]
        # 查找对应参数，无匹配则返回 [0,0,0,0,0]
        params = buff_id_to_params.get(buff_id, [0, 0, 0, 0, 0])
        result.append(params)
    
    return result

# ===================== 3. 解析EFFECT的函数 =====================
def parse_effect(effect_arr):
    """
    解析effect数组，按两个一组拆分为二维列表
    :param effect_arr: 扁平的effect数组，如 [1,1,5,222]
    :return: 二维列表，如 [[1,1],[5,222]]
    """
    # 异常处理：非列表/空列表/长度非偶数，返回空列表
    if not isinstance(effect_arr, list) or len(effect_arr) == 0 or len(effect_arr) % 2 != 0:
        print("effect数组格式错误：非列表/空列表/长度非偶数")
        return []
    
    result = []
    # 步长2遍历，每个组组成 [类型ID, 数值] 的子列表
    for i in range(0, len(effect_arr), 2):
        effect_id = effect_arr[i]
        effect_value = effect_arr[i + 1]
        result.append([effect_id, effect_value])
    
    return result

